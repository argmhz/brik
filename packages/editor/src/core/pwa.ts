import { encodePng } from "./png";

/*
 * Offline play and "install" for exported games (a PWA): a service worker
 * that keeps the game's files in the browser, a web manifest and icons.
 * Everything uses relative paths, so the game works in any folder or sub-path
 * (itch.io, GitHub Pages, a CDN).
 */

/** A short hash of file names and contents. Changes whenever anything in the game does. */
export function contentHash(files: Record<string, Uint8Array>): string {
  let h = 0x811c9dc5;
  const feed = (b: number) => {
    h ^= b;
    h = Math.imul(h, 0x01000193);
  };
  for (const path of Object.keys(files).sort()) {
    for (let i = 0; i < path.length; i++) feed(path.charCodeAt(i) & 0xff);
    feed(0);
    for (const b of files[path]) feed(b);
    feed(1);
  }
  return (h >>> 0).toString(16).padStart(8, "0");
}

export interface ServiceWorkerOptions {
  /** Files to fetch when the worker installs (paths relative to the game). */
  precache: string[];
  /** Names the cache; a new value replaces the old cache. */
  version: string;
}

/**
 * The service worker. Cache first: after the first visit the game starts
 * without a network. A new export has a new `version`: it installs in the
 * background and takes over on the next visit, and the old cache is deleted.
 * Files that weren't precached (e.g. the physics engine of a game that starts
 * using it later) are saved the first time they are fetched.
 */
export function serviceWorkerSource(opts: ServiceWorkerOptions): string {
  return `// Brik game service worker: offline play. Generated by the Brik export.
const VERSION = ${JSON.stringify(opts.version)};
// scope in the name: other games on the same site (a GitHub Pages user site) keep their own caches
const PREFIX = "brik:" + self.registration.scope + ":";
const CACHE = PREFIX + VERSION;
const FILES = ${JSON.stringify(opts.precache)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(FILES))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith(PREFIX) && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  event.respondWith(
    caches.match(request, { cacheName: CACHE, ignoreSearch: true }).then(
      (hit) =>
        hit ||
        fetch(request).then((response) => {
          if (response.ok) {
            const copy = response.clone();
            caches.open(CACHE).then((cache) => cache.put(request, copy));
          }
          return response;
        }),
    ),
  );
});
`;
}

/** The web app manifest. `icons` are paths relative to the game with their pixel size. */
export function webManifest(title: string, icons: { src: string; size: number }[]): string {
  return `${JSON.stringify(
    {
      name: title,
      short_name: title.length > 12 ? title.slice(0, 12).trim() : title,
      start_url: ".",
      scope: ".",
      display: "fullscreen",
      orientation: "any",
      background_color: "#000000",
      theme_color: "#111216",
      icons: icons.map((i) => ({ src: i.src, sizes: `${i.size}x${i.size}`, type: "image/png", purpose: "any" })),
    },
    null,
    2,
  )}\n`;
}

/** Registers the service worker, quietly: it only matters where it works (http and https). */
export const REGISTER_SERVICE_WORKER = `if ("serviceWorker" in navigator && location.protocol.startsWith("http")) {
      addEventListener("load", () => navigator.serviceWorker.register("sw.js").catch(() => {}));
    }`;

/**
 * A plain icon: a blue disc with a white play triangle on a dark square.
 * Used when the project has no icon.png of its own.
 */
export function defaultIcon(size: number): Uint8Array {
  const rgba = new Uint8Array(size * size * 4);
  const c = size / 2;
  const radius = size * 0.4;
  // play triangle: left edge at x0, tip at x1
  const x0 = c - size * 0.1;
  const x1 = c + size * 0.17;
  const half = size * 0.17;
  const inTriangle = (x: number, y: number) => x >= x0 && x <= x1 && Math.abs(y - c) <= (half * (x1 - x)) / (x1 - x0);
  const sub = [0.25, 0.75];
  for (let y = 0; y < size; y++) {
    for (let x = 0; x < size; x++) {
      // 2x2 samples per pixel, so the edges are smooth
      let disc = 0;
      let tri = 0;
      for (const sy of sub) {
        for (const sx of sub) {
          const px = x + sx;
          const py = y + sy;
          if (Math.hypot(px - c, py - c) <= radius) disc++;
          if (inTriangle(px, py)) tri++;
        }
      }
      const d = disc / 4;
      const t = tri / 4;
      // dark square, blue disc over it, white triangle over that
      const mix = (bg: number, fg: number, a: number) => bg * (1 - a) + fg * a;
      const o = (y * size + x) * 4;
      const r = mix(mix(17, 76, d), 255, t);
      const g = mix(mix(18, 141, d), 255, t);
      const b = mix(mix(22, 255, d), 255, t);
      rgba[o] = Math.round(r);
      rgba[o + 1] = Math.round(g);
      rgba[o + 2] = Math.round(b);
      rgba[o + 3] = 255;
    }
  }
  return encodePng(size, size, rgba);
}
